// Writes e2e/SCREENS.md from what the last run of screens.spec.ts measured (test-results/screens/*.json):
// every screen and state, where it was driven, and what was found. Run it after the pass:
//   pnpm --filter koppel.ui e2e:report
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../test-results/screens/', import.meta.url);
const runs = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(new URL(f, dir), 'utf8')));
if (!runs.length) throw new Error('No results: run `pnpm --filter koppel.ui e2e e2e/screens.spec.ts` first.');

const byId = new Map();
for (const r of runs) {
  const row = byId.get(r.id) ?? { what: r.what, driven: new Set(), found: [] };
  row.driven.add(`${r.width} ${r.scheme}`);
  for (const f of r.findings) row.found.push({ ...f, at: `${r.width} ${r.scheme}` });
  byId.set(r.id, row);
}

const kinds = new Map();
for (const row of byId.values()) for (const f of row.found) {
  const key = `${f.known ? 'known' : f.kind === 'clipped' ? 'note' : 'open'}|${f.kind}|${f.known ?? ''}`;
  kinds.set(key, (kinds.get(key) ?? 0) + 1);
}

const lines = [
  '# Screens driven before a release',
  '',
  'Generated by `pnpm --filter koppel.ui e2e:report` from the last run of `e2e/screens.spec.ts`. Do not edit by hand.',
  '',
  `Every row was driven in Chromium at desktop width (1120 px) and phone width (390 px), in light and dark, with the service's answers stood in (\`e2e/support.ts\`). Each run measured: sideways scroll, anything past the edge, console errors, controls with no name, touch targets under 40 px on a phone, text contrast under 4.5:1 (3:1 for large text), and text cut by an ellipsis. Each also took a picture (test-results/screens, not kept in git).`,
  '',
  '## What the measurements found',
  '',
  '| Kind | Count | Status |',
  '|---|---|---|',
  ...[...kinds].sort().map(([key, n]) => {
    const [status, kind, why] = key.split('|');
    return `| ${kind} | ${n} | ${status === 'known' ? why : status === 'note' ? 'By design: an ellipsis with a tooltip (a fingerprint, a long name), or Heartwood\'s tab label' : 'Open'} |`;
  }),
  '',
  '## Not covered by this pass',
  '',
  '- Colour vision mode (`-safe` themes): not driven.',
  '- Widths between the two: the tablet range around the 800 px breakpoint where a panel turns into a sheet.',
  '- Hover and keyboard: tooltips on cut values, focus order and focus rings (`focus.spec.ts` covers the page heading only).',
  '- A live link that drops and returns on its own: the down state is reached by failing the stand-in stream, never by a real outage.',
  '- Anything that needs a real service: USB attaching, two servers at once, the Windows tray, the installers.',
  '',
  '## Screens and states',
  '',
  '| Screen or state | What it is | Driven | Open findings |',
  '|---|---|---|---|',
  ...[...byId].map(([id, row]) => {
    const open = row.found.filter((f) => !f.known && f.kind !== 'clipped');
    return `| \`${id}\` | ${row.what} | ${[...row.driven].sort().join(', ')} | ${open.length ? open.map((f) => `${f.kind}: ${f.detail} (${f.at})`).join('; ') : 'none'} |`;
  }),
  '',
];
writeFileSync(new URL('./SCREENS.md', import.meta.url), lines.join('\n'));
console.log(`SCREENS.md: ${byId.size} screens and states, ${runs.length} runs.`);
