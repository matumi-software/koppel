<#
.SYNOPSIS
Builds Koppel's Windows installer: bin\Koppel-Setup.exe.

.DESCRIPTION
0. Checks the vendored usbip-win2 files against SHA256SUMS, the signer certificates pinned in this script and the pinned hashes of the unsigned DLLs, and fails on any mismatch.
1. Builds the UI (npm dependencies from the lock file, the build fails if they have drifted), then
   Koppel's Rust programs, release, with the C runtime linked in (src\.cargo\config.toml), from
   Cargo.lock (--locked): Koppel.exe, the service and the commands, with the UI inside it, and
   KoppelDesktop.exe, the tray icon and the Start menu entry.
2. Adds usbip-win2's driver and tools (from usbip-win2\<version>, see export-usbip-win2.ps1),
   the install scripts and the third-party notices (..\notices\new-notices.ps1, which needs
   cargo-about; the Linux build uses the same script).
3. Builds the MSI, then setup.exe, which installs the VC++ runtime first: usbip-win2's tools link it
   dynamically, though Koppel's own programs do not need it.

Run from anywhere: .\build.ps1 [-Version 0.2.0]. Without -Version it uses the workspace version in src\Cargo.toml.
The Rust toolchain (cargo) must be on PATH, with CARGO_HOME and RUSTUP_HOME set if they are not the defaults.
#>
[CmdletBinding()]
param(
    [string]$Version
)

$ErrorActionPreference = 'Stop'
$installer = $PSScriptRoot
# src\installer\windows: two folders up is src\.
$src = Split-Path (Split-Path $installer)
$ui = Join-Path $src 'ui'
$staging = Join-Path $installer 'obj\staging'
$cache = Join-Path $installer 'obj\cache'
$out = Join-Path $installer 'bin'

if (-not $Version) {
    # The first version line after [workspace.package] in src\Cargo.toml.
    $inPackage = $false
    foreach ($line in Get-Content (Join-Path $src 'Cargo.toml')) {
        if ($line -match '^\s*\[') { $inPackage = $line -match '^\s*\[workspace\.package\]' ; continue }
        if ($inPackage -and $line -match '^\s*version\s*=\s*"([^"]+)"') { $Version = $Matches[1]; break }
    }
    if (-not $Version) { throw 'No version under [workspace.package] in src\Cargo.toml. Pass -Version.' }
}
Write-Host "Version $Version"

function Invoke-Checked([scriptblock]$command) {
    & $command
    if ($LASTEXITCODE -ne 0) { throw "Failed with exit code $LASTEXITCODE`: $command" }
}

# What each vendored usbip-win2 version must look like, kept here and not in SHA256SUMS: that file is
# regenerated by export-usbip-win2.ps1 -SumsOnly, so on its own it could be rewritten to match a swapped
# file. Signed files are pinned by the signer certificate's thumbprint, the two DLLs (unsigned upstream)
# by hash. A new version needs a new entry: take the values from a copy you have checked by hand.
$usbipWin2Pins = @{
    '0.9.8.1' = @{
        # .exe: Cloudyne Systems (Scheibling Consulting AB), the publisher of the official release.
        ExeSigner = '9AC56B6C76141395D74FFF6652818376E80B9C95'
        # .sys and .cat: Microsoft Windows Hardware Compatibility Publisher.
        DriverSigner = '32B4E7CE92A59C722B8BDF7AE3E66520CFB9DE21'
        Unsigned = @{
            'tools/libusbip.dll' = 'f123ef5d288b817a890cbe39a3c2d212b3d8b1765c691c8703ccb76c7337986c'
            'tools/resources.dll' = '4bfc862e5891d9b4c12a8ebd43d3ba871ebf94b65f7a00c22527c905949e0fff'
        }
    }
}

# The vendored usbip-win2 files must be the ones export-usbip-win2.ps1 recorded in SHA256SUMS, anything
# signed must carry the signer pinned above, and the unsigned DLLs must match their pinned hashes.
function Test-UsbipWin2([string]$folder, [string]$version) {
    $pins = $usbipWin2Pins[$version]
    if (-not $pins) { throw "No signer and hash pins for usbip-win2 $version in build.ps1 (`$usbipWin2Pins). Add them from a copy you have checked." }
    $sumsFile = Join-Path $folder 'SHA256SUMS'
    if (-not (Test-Path $sumsFile)) { throw "$sumsFile is missing. Run export-usbip-win2.ps1 -SumsOnly." }
    $expected = @{}
    foreach ($line in Get-Content $sumsFile) {
        if ($line -match '^\s*(#|$)') { continue }
        if ($line -notmatch '^([0-9a-f]{64}) [ *](.+)$') { throw "Unreadable line in SHA256SUMS: $line" }
        $expected[$Matches[2]] = $Matches[1]
    }
    $problems = New-Object System.Collections.Generic.List[string]
    $actual = Get-ChildItem $folder -Recurse -File | Where-Object Name -ne 'SHA256SUMS'
    foreach ($file in $actual) {
        $relative = $file.FullName.Substring($folder.Length).TrimStart('\').Replace('\', '/')
        if (-not $expected.ContainsKey($relative)) { $problems.Add("$relative is not in SHA256SUMS"); continue }
        if ((Get-FileHash $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant() -ne $expected[$relative]) { $problems.Add("$relative does not match SHA256SUMS"); continue }
        $kind = $file.Extension.ToLowerInvariant()
        if ($kind -notin '.exe', '.dll', '.sys', '.cat') { continue }
        $signature = Get-AuthenticodeSignature $file.FullName
        if ($signature.Status -eq 'NotSigned' -and $kind -eq '.dll') {
            $hash = (Get-FileHash $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
            if (-not $pins.Unsigned.ContainsKey($relative)) { $problems.Add("$relative is unsigned and has no pinned hash in build.ps1") }
            elseif ($pins.Unsigned[$relative] -ne $hash) { $problems.Add("$relative does not match the hash pinned in build.ps1") }
            continue
        }
        if ($signature.Status -ne 'Valid') { $problems.Add("$relative signature is $($signature.Status)"); continue }
        $wanted = if ($kind -eq '.exe') { $pins.ExeSigner } else { $pins.DriverSigner }
        if ($signature.SignerCertificate.Thumbprint -ne $wanted) { $problems.Add("$relative is signed by '$($signature.SignerCertificate.Subject)' ($($signature.SignerCertificate.Thumbprint)), not by the pinned certificate $wanted") }
    }
    foreach ($name in $pins.Unsigned.Keys) {
        if (-not (Test-Path (Join-Path $folder $name))) { $problems.Add("$name is pinned in build.ps1 but missing") }
    }
    foreach ($name in $expected.Keys) {
        if (-not (Test-Path (Join-Path $folder $name))) { $problems.Add("$name is in SHA256SUMS but missing") }
    }
    if ($problems.Count) { throw ("The usbip-win2 files cannot be trusted:`n  " + ($problems -join "`n  ")) }
}

Remove-Item $staging -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $staging, $cache, $out | Out-Null

Write-Host 'Building the UI...'
Invoke-Checked { pnpm --dir $ui install --frozen-lockfile }
Invoke-Checked { pnpm --dir $ui --filter koppel.ui build }

Write-Host 'Building Koppel...'
# Koppel.exe stays a console program, for the service and for commands such as --reset-password;
# KoppelDesktop.exe is built as a Windows program (windows_subsystem), so neither the tray nor the Start
# menu entry opens a console window.
Invoke-Checked { cargo build --manifest-path (Join-Path $src 'Cargo.toml') --release --locked -p koppel -p koppel-windows }
$release = Join-Path $src 'target\release'
Copy-Item (Join-Path $release 'koppel.exe') (Join-Path $staging 'Koppel.exe')
Copy-Item (Join-Path $release 'koppel-desktop.exe') (Join-Path $staging 'KoppelDesktop.exe')

Write-Host 'Writing the third-party notices...'
& (Join-Path (Split-Path $installer) 'notices\new-notices.ps1') -Target x86_64-pc-windows-msvc -Output (Join-Path $staging 'THIRD-PARTY-NOTICES.txt')

$usbipWin2 = Get-ChildItem (Join-Path $installer 'usbip-win2') -Directory | Sort-Object { [version]$_.Name } | Select-Object -Last 1
if (-not $usbipWin2) { throw 'No usbip-win2 files. Run export-usbip-win2.ps1 first.' }
Write-Host "Checking usbip-win2 $($usbipWin2.Name)..."
Test-UsbipWin2 $usbipWin2.FullName $usbipWin2.Name
Write-Host "Adding usbip-win2 $($usbipWin2.Name)..."
$usbip = Join-Path $staging 'usbip'
New-Item -ItemType Directory -Force -Path (Join-Path $usbip 'drivers') | Out-Null
Copy-Item (Join-Path $usbipWin2.FullName 'tools\*') $usbip
Copy-Item (Join-Path $usbipWin2.FullName 'usbip2_ude'), (Join-Path $usbipWin2.FullName 'usbip2_filter') (Join-Path $usbip 'drivers') -Recurse
Copy-Item (Join-Path $installer 'driver.ps1'), (Join-Path $installer 'data-folder.ps1') $usbip

# The notices for what Koppel's programs carry (Rust crates, npm) are in staging; add the Windows-only ones.
$windowsNotices = @(
    ''
    "== usbip-win2 $($usbipWin2.Name) (driver, usbip.exe, devnode.exe, libusbip.dll) =="
    'https://github.com/vadimgrn/usbip-win2'
    ''
    (Get-Content (Join-Path $usbipWin2.FullName 'LICENSE.txt') -Raw)
    '== CLI11 (compiled into usbip.exe) =='
    'https://github.com/CLIUtils/CLI11'
    ''
    (Get-Content (Join-Path $usbipWin2.FullName 'CLI11-LICENSE.txt') -Raw)
    '== Microsoft Visual C++ Redistributable =='
    'Installed by Koppel-Setup.exe under Microsoft''s own licence terms, which it shows when run on its own.'
    ''
)
Add-Content -Path (Join-Path $staging 'THIRD-PARTY-NOTICES.txt') -Value ($windowsNotices -join "`r`n") -Encoding utf8

$vcRedist = Join-Path $cache 'vc_redist.x64.exe'
if (-not (Test-Path $vcRedist)) {
    Write-Host 'Downloading the VC++ runtime...'
    Invoke-WebRequest 'https://aka.ms/vs/17/release/vc_redist.x64.exe' -OutFile $vcRedist -UseBasicParsing
}
$signature = Get-AuthenticodeSignature $vcRedist
if ($signature.Status -ne 'Valid' -or $signature.SignerCertificate.Subject -notmatch 'O=Microsoft Corporation') {
    throw "vc_redist.x64.exe is not signed by Microsoft ($($signature.Status)). Delete $vcRedist and try again."
}
$vcRedistBuild = (Get-Item $vcRedist).VersionInfo.FileBuildPart

Write-Host 'Building the MSI...'
$msiOut = Join-Path $installer 'obj\msi'
Invoke-Checked { dotnet build (Join-Path $installer 'Koppel.Installer\Koppel.Installer.wixproj') -c Release -nologo -v q -o $msiOut -p:RestoreLockedMode=true -p:StagingDir=$staging -p:Version=$Version }

Write-Host 'Building setup.exe...'
Invoke-Checked { dotnet build (Join-Path $installer 'Koppel.Setup\Koppel.Setup.wixproj') -c Release -nologo -v q -o $out -p:RestoreLockedMode=true -p:Version=$Version -p:Msi=$(Join-Path $msiOut 'Koppel.msi') -p:Notices=$(Join-Path $staging 'THIRD-PARTY-NOTICES.txt') -p:VCRedist=$vcRedist -p:VCRedistBuild=$vcRedistBuild }

$setup = Join-Path $out 'Koppel-Setup.exe'
Write-Host "Built $setup ($([math]::Round((Get-Item $setup).Length / 1MB, 1)) MB)"
